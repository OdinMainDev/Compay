CREATE TABLE "log_transactions" (
    "id" bigserial,
    "payment_id" bigint,
    "payment_trx_id" varchar(36),
    "withdraw_id" bigint,
    "withdraw_trx_id" varchar(36),
    "merchant_wallet_id" bigint,
    "merchant_id" int,
    "currency" varchar(20),
    "is_complete" boolean,
    "is_spent" boolean,
    "start_block" int,
    "tx_id" varchar(255),
    "tx_hash" varchar(255),
    "address" varchar(128),
    "data" jsonb,
    "created_at" int,
    "updated_at" int,
    PRIMARY KEY ("id")
);