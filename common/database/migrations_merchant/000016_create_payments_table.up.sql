CREATE TABLE "payments" (
    "id" bigserial,
    "trx_id" varchar(36),
    "merchant_id" int,
    "currency" varchar(20),
    "status" varchar(20),
    "address" varchar(255),
    "amount" int,
    "amount_usd" int,
    "received_amount" int,
    "received_amount_usd" int,
    "private_key" text,
    "private_key_wif" text,
    "public_key" text,
    "public_key_full" text,
    "expires_at" int,
    "created_at" int,
    "updated_at" int,
    PRIMARY KEY ("id")
);